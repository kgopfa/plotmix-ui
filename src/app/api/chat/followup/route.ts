import { NextRequest, NextResponse } from 'next/server';
import { getServerSession } from 'next-auth';
import { authOptions } from '@/lib/auth';
import { FollowUpChatRequest, FollowUpChatResponse, ChatMessage } from '@/types/project-generation';

export async function POST(request: NextRequest) {
  try {
    // Check authentication
    const session = await getServerSession(authOptions);
    if (!session) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }

    const body: FollowUpChatRequest = await request.json();
    const { contentId, message } = body;

    if (!contentId || !message || !message.trim()) {
      return NextResponse.json({ error: 'Content ID and message are required' }, { status: 400 });
    }

    // TODO: Integrate with actual AI service/backend
    // For now, we'll simulate the response
    
    // Simulate AI processing time
    await new Promise(resolve => setTimeout(resolve, 500));

    // Create mock response
    const aiResponse: ChatMessage = {
      id: Date.now().toString(),
      message: `I understand your follow-up question: "${message}". This is a simulated response that would be generated by the AI service. In a real implementation, this would be processed by your AI backend and return relevant information about the content.`,
      isUser: false,
      timestamp: new Date().toISOString()
    };

    const response: FollowUpChatResponse = {
      message: aiResponse,
      updatedChatHistory: [
        // This would typically include the existing chat history plus the new messages
        {
          id: (Date.now() - 1).toString(),
          message: message,
          isUser: true,
          timestamp: new Date().toISOString()
        },
        aiResponse
      ]
    };

    return NextResponse.json(response);
  } catch (error) {
    console.error('Follow-up chat API error:', error);
    return NextResponse.json(
      { error: 'Internal server error' },
      { status: 500 }
    );
  }
} 